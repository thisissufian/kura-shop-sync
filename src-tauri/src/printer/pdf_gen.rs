use base64::{engine::general_purpose::STANDARD, Engine};
use std::path::Path;

use crate::models::{BillReceipt, PdfExportResult};
use crate::printer::format_minor_money;

fn pdf_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for ch in s.chars() {
        match ch {
            '(' => out.push_str("\\("),
            ')' => out.push_str("\\)"),
            '\\' => out.push_str("\\\\"),
            c if c.is_ascii() => out.push(c),
            _ => out.push('?'),
        }
    }
    out
}

fn push_line(stream: &mut String, font: &str, size: u8, x: f32, y: f32, text: &str) {
    let esc = pdf_escape(text);
    stream.push_str(&format!(
        "BT /{font} {size} Tf 1 0 0 1 {x:.1} {y:.1} Tm ({esc}) Tj ET\n"
    ));
}

pub fn generate_receipt_pdf(
    out_dir: &Path,
    shop_name: &str,
    shop_subtitle: &str,
    currency_symbol: &str,
    receipt_footer: &str,
    bill: &BillReceipt,
) -> Result<PdfExportResult, String> {
    std::fs::create_dir_all(out_dir).map_err(|e| format!("Create PDF dir: {e}"))?;
    let width_pt: f32 = 226.0; // ~80mm thermal roll width
    let line_h: f32 = 12.5;
    let has_sub = !shop_subtitle.trim().is_empty();
    let total_lines = 12
        + usize::from(has_sub)
        + bill.items.len()
        + usize::from(bill.discount_minor > 0);
    let height_pt = (64.0 + (total_lines as f32) * line_h).max(240.0);

    let mut content = String::with_capacity(2048);
    let mut y = height_pt - 24.0;

    push_line(&mut content, "F2", 11, 14.0, y, shop_name);
    y -= 13.0;
    if has_sub {
        push_line(&mut content, "F1", 7, 14.0, y, shop_subtitle.trim());
        y -= 11.0;
    }
    if bill.voided {
        push_line(&mut content, "F2", 9, 14.0, y, "*** VOIDED RECEIPT ***");
        y -= line_h;
    }
    let dt = bill.hlc.get(..19).unwrap_or(&bill.hlc).replace('T', " ");
    push_line(&mut content, "F1", 8, 14.0, y, &format!("Bill: {}", bill.bill_no));
    y -= 11.0;
    push_line(&mut content, "F1", 8, 14.0, y, &format!("Time: {dt} UTC"));
    y -= 11.0;
    push_line(
        &mut content,
        "F1",
        8,
        14.0,
        y,
        &format!("Pay: {}  Node: {}", bill.payment_mode, bill.node_id),
    );
    y -= 11.0;
    push_line(&mut content, "F1", 8, 14.0, y, "----------------------------------------");
    y -= 11.0;
    push_line(&mut content, "F2", 8, 14.0, y, "Item                Qty           Total");
    y -= 11.0;
    push_line(&mut content, "F1", 8, 14.0, y, "----------------------------------------");
    y -= 11.0;

    for item in &bill.items {
        let short_name: String = item.name.chars().take(19).collect();
        let tot = format_minor_money(item.line_total_minor, currency_symbol);
        let row = format!("{short_name:<19} {:>3} {:>16}", item.qty, tot);
        push_line(&mut content, "F1", 8, 14.0, y, &row);
        y -= line_h;
    }

    push_line(&mut content, "F1", 8, 14.0, y, "----------------------------------------");
    y -= 12.0;
    if bill.discount_minor > 0 {
        let disc = format_minor_money(-bill.discount_minor, currency_symbol);
        push_line(&mut content, "F1", 8, 14.0, y, &format!("{:<24}{:>16}", "Discount", disc));
        y -= line_h;
    }
    let grand = format_minor_money(bill.total_minor, currency_symbol);
    push_line(&mut content, "F2", 9, 14.0, y, &format!("{:<20}{:>15}", "TOTAL", grand));
    y -= 16.0;
    let footer = if receipt_footer.trim().is_empty() {
        "Thank you for shopping!"
    } else {
        receipt_footer.trim()
    };
    push_line(&mut content, "F1", 8, 14.0, y, footer);
    y -= 11.0;
    push_line(&mut content, "F1", 7, 14.0, y, "Generated by Kura Offline POS");

    let stream_bytes = content.as_bytes();
    let objs = [
        "1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n".to_string(),
        "2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n".to_string(),
        format!(
            "3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {width_pt:.0} {height_pt:.0}] /Contents 4 0 R /Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> >>\nendobj\n"
        ),
        format!(
            "4 0 obj\n<< /Length {} >>\nstream\n{content}endstream\nendobj\n",
            stream_bytes.len()
        ),
        "5 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>\nendobj\n".to_string(),
        "6 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Courier-Bold >>\nendobj\n".to_string(),
    ];

    let mut pdf = Vec::with_capacity(4096);
    pdf.extend_from_slice(b"%PDF-1.4\n");
    let mut offsets = Vec::with_capacity(objs.len());
    for obj in &objs {
        offsets.push(pdf.len());
        pdf.extend_from_slice(obj.as_bytes());
    }
    let xref_pos = pdf.len();
    pdf.extend_from_slice(format!("xref\n0 {}\n0000000000 65535 f \n", objs.len() + 1).as_bytes());
    for off in offsets {
        pdf.extend_from_slice(format!("{off:010} 00000 n \n").as_bytes());
    }
    pdf.extend_from_slice(
        format!(
            "trailer\n<< /Size {} /Root 1 0 R >>\nstartxref\n{xref_pos}\n%%EOF\n",
            objs.len() + 1
        )
        .as_bytes(),
    );

    let safe_name = bill.bill_no.replace(['/', '\\', ':'], "_");
    let file_path = out_dir.join(format!("{safe_name}.pdf"));
    std::fs::write(&file_path, &pdf).map_err(|e| format!("Write PDF: {e}"))?;
    let data_url = format!("data:application/pdf;base64,{}", STANDARD.encode(&pdf));
    Ok(PdfExportResult {
        file_path: file_path.to_string_lossy().into_owned(),
        data_url,
        size_bytes: pdf.len(),
    })
}
